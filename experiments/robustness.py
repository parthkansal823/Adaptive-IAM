"""Paired bootstrap and independent-seed replication of the frozen risk model.

No test results select models, parameters or thresholds. Replication batches use
the same synthetic distribution and do not establish real-world validity.
"""
from __future__ import annotations

import argparse
import importlib.metadata
import json
import platform
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from backend.app.risk import RiskEngine, SEED, dataset, metrics  # noqa: E402


def measurements(y, p, classification_threshold, policy_threshold):
    positive, negative = y == 1, y == 0
    predictions = p >= classification_threshold
    tp = np.sum(predictions & positive)
    fp = np.sum(predictions & negative)
    fn = np.sum(~predictions & positive)
    return {
        "f1": float(2*tp / max(1, 2*tp+fp+fn)),
        "brier_score": float(np.mean((p-y)**2)),
        "policy_detection_recall": float(np.mean(p[positive] >= policy_threshold)),
        "legitimate_friction_rate": float(np.mean(p[negative] >= policy_threshold)),
    }


def bootstrap(y, raw, candidate, engine, repetitions):
    rng = np.random.default_rng(SEED+100)
    baseline = measurements(y, raw, .5, .3)
    improved = measurements(y, candidate, engine.threshold, engine.low_threshold)
    differences = {key: [] for key in baseline}
    negative = np.flatnonzero(y == 0)
    positive = np.flatnonzero(y == 1)
    # Stratified paired resampling preserves observed class counts; identical
    # selected event indices are used for both methods in every replicate.
    for _ in range(repetitions):
        idx = np.concatenate([rng.choice(negative, len(negative), replace=True), rng.choice(positive, len(positive), replace=True)])
        a = measurements(y[idx], raw[idx], .5, .3)
        b = measurements(y[idx], candidate[idx], engine.threshold, engine.low_threshold)
        for key in differences:
            differences[key].append(b[key]-a[key])
    return {key: {"baseline": baseline[key], "candidate": improved[key], "difference_candidate_minus_baseline": improved[key]-baseline[key], "ci95": [float(v) for v in np.quantile(values, [.025, .975])]} for key, values in differences.items()}


def subgroup_metrics(x, y, raw, candidate, engine):
    report = []
    for index, feature in [(0, "device"), (1, "location")]:
        for value, label in [(0, "known"), (1, "new")]:
            mask = x[:, index] == value
            if np.sum(y[mask] == 0) < 20 or np.sum(y[mask] == 1) < 20:
                continue
            report.append({"group": f"{label}_{feature}", "events": int(mask.sum()), "suspicious": int(y[mask].sum()),
                           "baseline": measurements(y[mask], raw[mask], .5, .3),
                           "candidate": measurements(y[mask], candidate[mask], engine.threshold, engine.low_threshold)})
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bootstrap", type=int, default=1000)
    parser.add_argument("--output", type=Path, default=ROOT / "experiments/robustness.json")
    args = parser.parse_args()
    if not 100 <= args.bootstrap <= 10000:
        parser.error("--bootstrap must be between 100 and 10000")
    engine = RiskEngine()
    x, y = dataset()
    x, y = x[8000:], y[8000:]
    raw, p = engine.raw(x), engine.probabilities(x)
    independent = []
    for seed in [SEED+i for i in range(1, 6)]:
        rows, labels = dataset(seed, n=2000)
        independent.append({"seed": seed, "events": len(labels), "suspicious_prevalence": float(labels.mean()),
                            "baseline": metrics(labels, engine.raw(rows), .5),
                            "candidate": metrics(labels, engine.probabilities(rows), engine.threshold, engine.low_threshold, engine.high_threshold)})
    report = {
        "model_version": engine.version,
        "protocol": {"frozen_model": True, "test_set_used_for_tuning": False, "bootstrap_repetitions": args.bootstrap, "bootstrap_seed": SEED+100, "resampling": "Paired class-stratified event bootstrap; percentile 95% intervals", "interpretation": "Conditional uncertainty for one trained model, not uncertainty across retraining or real-world distributions", "replication": "Five new independently generated 2000-event batches; no refitting"},
        "environment": {"python": platform.python_version(), "platform": platform.platform(), **{name: importlib.metadata.version(name) for name in ["numpy", "scikit-learn", "joblib"]}},
        "paired_comparison": bootstrap(y, raw, p, engine, args.bootstrap),
        "subgroups": subgroup_metrics(x, y, raw, p, engine),
        "independent_seed_replication": independent,
        "limitations": ["All outcomes are synthetic and generated by the same mechanism as training.", "New seeds do not represent distribution shift, new organizations or real users.", "Bootstrap intervals are exploratory and unadjusted for multiple comparisons.", "Device/location subgroup differences are diagnostics, not a demographic fairness evaluation.", "Lower benign friction can come with lower attack detection; both are disclosed.", "NLP, LLM quality, decentralized blockchain performance and production MFA are not evaluated by this experiment."],
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2)+"\n", encoding="utf-8")
    print(json.dumps({"output": str(args.output), "paired_comparison": report["paired_comparison"]}, indent=2))


if __name__ == "__main__":
    main()
